import collections

import bank

ROW = "仕入（現金）"
# 引出した口座 → PLタブ。本体(3351509)と横丁(3543920)はここに入れない（①の判断）
STORE_ACCOUNT = {
    "千葉銀行（もも焼き）": "もも焼きJAPAN",
    "千葉銀行（りゅうちゃん）": "りゅうちゃん",
    "千葉銀行（タコハイ）": "タコとハイボール",
    "千葉銀行（ハナ）": "韓国酒場ハナ",
    "千葉銀行（焼きたて屋）": "焼きたて屋",
    "千葉銀行（十三里屋）": "さわら十三里屋",
}
# 費用にしない口座（記録として残す）
NOT_EXPENSE = {"千葉銀行": "本体（ビルメンのメイン口座）",
               "千葉銀行（横丁）": "神栖横丁"}

RAW = "ＣＤ"          # 千葉銀行の摘要。ATM引出はこれ1本
MONTH = {"2025/09": "9月", "2025/10": "10月", "2025/11": "11月", "2025/12": "12月",
         "2026/01": "1月", "2026/02": "2月", "2026/03": "3月", "2026/04": "4月",
         "2026/05": "5月", "2026/06": "6月", "2026/07": "7月", "2026/08": "8月"}


def _ex(inc):
    """引出額（税込）から税抜Xを逆算。X + floor(X*10/100) == inc なるX。"""
    base = inc * 100 // 110
    for x in (base - 1, base, base + 1, base + 2):
        if x + x * 10 // 100 == inc:
            return x, True
    return base, False


def _withdrawals():
    """{銀行: {月: [(日付, 金額, 元ファイル)]}}"""
    d = collections.defaultdict(lambda: collections.defaultdict(list))
    for r in bank._load_chiba():
        if r["raw"] != RAW:
            continue
        ym = r["date"][:7]
        if ym not in MONTH:
            continue
        d[r["bank"]][MONTH[ym]].append((r["date"], r["amount"], r["src"]))
    return d


def rows():
    """(タブ, PL行, 月, 税抜, 元ファイル, メモ) を列挙。店舗口座ぶんだけ。"""
    d = _withdrawals()
    for acct, tab in STORE_ACCOUNT.items():
        for m, det in sorted(d[acct].items()):
            inc = sum(a for _dt, a, _s in det)
            ex, exact = _ex(inc)
            what = "／".join(f"{dt} {a:,}" for dt, a, _s in sorted(det))
            note = (f"{acct}のATM引出 {len(det)}件: {what}＝{inc:,}（税込）"
                    f" → 税抜{ex:,}。"
                    "店舗口座の引出は現金仕入とみて全額を仕入（現金）に入れる"
                    "（利用者判断 2026-08-25「店舗口座のは全部仕入にしよう」）。"
                    "計上月は引出した月そのまま"
                    + ("" if exact else "。端数が割り切れず切り捨て"))
            yield tab, ROW, m, ex, f"銀行明細/21期/{det[0][2]}", note


def hold_rows():
    """費用にしなかった大口引出と、小口現金の元資料待ちを記録に残す。"""
    d = _withdrawals()
    for acct, what in NOT_EXPENSE.items():
        det = [(m, dt, a) for m in d[acct] for dt, a, _s in d[acct][m]]
        if not det:
            continue
        tot = sum(a for _m, _dt, a in det)
        yield ("通年", what, f"ATM引出（{acct}）",
               f"{len(det)}件 計{tot:,}円。★費用にしていない（利用者判断 2026-08-25）。"
               "下ろしただけでは預金→現金の振替で貸借の動きだけ。"
               "100,000／200,000／300,000という丸い金額で給料日前後に集中しており、"
               "釣銭準備金・仮払・立替の類とみられる。使い道の資料"
               "（小口現金出納帳・レシート）が出てきたら、そこで費用にする")
    yield ("通年", "（全社）", "現金で払った経費（小口現金）",
           "書類（CSV/PDF）からは拾えない経路。小口現金出納帳・レシート・日報が要る"
           "（利用者が探し中 2026-08-25）。既存21期PLに入っているのは年193,041円ぶん"
           "（業務課その他、仕入（小口）77,440／神栖横丁その他、仕入（小口）100,377"
           "／りゅうちゃん仕入（現金）14,318／タコとハイボール仕入（現金）906）。"
           "★8月は既存PLを使わない方針なので、資料が来ないと現金経費はゼロのまま")


def check(wb=None):
    """引出の総額と計上した税込の総額が合うか／行があるか／書き込み先が空か。"""
    d = _withdrawals()
    want = sum(a for acct in STORE_ACCOUNT for m in d[acct]
               for _dt, a, _s in d[acct][m])
    got = 0
    for _t, _r, _m, _ex, _s, note in rows():
        got += int(note.split("＝")[1].split("（税込）")[0].replace(",", ""))
    assert want == got, f"引出の総額 {want:,} ≠ 計上した税込 {got:,}"
    if wb is None:
        return
    import build2
    for tab, row, m, val, _s, _n in rows():
        assert row in build2.RIDX[tab], f"{tab} に「{row}」行が無い"


if __name__ == "__main__":
    check()
    print("店舗口座のATM引出 → 仕入（現金）\n")
    tot = 0
    for tab, row, m, v, _s, note in rows():
        print(f"{tab:<14}{m:<4}{v:>8,}   {note.split('＝')[0]}")
        tot += v
    print(f"\n計 {tot:,}円（税抜）")
    print("\n費用にしないもの／資料待ち:")
    for m, tab, item, why in hold_rows():
        print(f"   [{tab}] {item}")
        print(f"        {why[:100]}…")
