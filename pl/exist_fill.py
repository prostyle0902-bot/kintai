def split_by_cards():
    """cards.py が費目別に割った (タブ, 一括行, 月) の集合。写してはいけないセル。"""
    import cards
    out = set()
    for tab, _merch, plrow, _ex, _tax, _src, m, _used, iss in cards.rows():
        if plrow is None:
            continue
        out.add((tab, _LUMP[iss], m))
    return out


