#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""地域活性舎からの事務代行手数料 → 本部「その他売上」（利用者指示 2026-09-03）

--- これは何か ------------------------------------------------------------
千葉銀行3351509（本体）に「（カ）チイキカツセイシヤ」から毎月33,000円の
定額入金が8件ある。**Prostyleが地域活性舎の事務を代行していた手数料**
（利用者確認 2026-09-03「これは事務手数料、事務代行してたので」）。
Prostyle側から見ると【売上】。

    2025/09/26  2025/10/31  2025/11/25  2025/12/25
    2026/01/27  2026/02/25  2026/03/26  2026/04/30    各 33,000 ／ 計 264,000

--- なぜPLに入っていなかったか --------------------------------------------
boardの請求一覧CSVに地域活性舎の請求が1件も無い。boardに載るのは請求書を
発行した売掛だけなので、board経由では入ってこない。請求書もDropboxの売掛に
無い（`※請求書※/売掛` を検索して0件）。**入金の記録が銀行にしか無い**。

★`bank.py` の `reconcile()` が見ているのは【出金】だけなので、この手の
  入金側の計上漏れは①②のリストには出てこない。口座ごとに
  `bank.tenants()` で摘要別に並べて目視するしかない。

--- 入れ先（利用者指示 2026-09-03「本部のその他売上で」）------------------
本部タブの「その他売上」。本部の売上行は21期を通して全月ゼロだったので、
ここが初めて入る値になる。

--- 税率と金額 ------------------------------------------------------------
33,000 = 30,000 × 1.1 ちょうど。事務代行は課税役務なので10%とみる。
    税込 33,000 → 税抜 30,000 ＋ 消費税 3,000
    8か月ぶん      税抜 240,000 ＋ 消費税 24,000（＝税込 264,000）
★請求書が無いので税率は請求書で確かめられていない。33,000が30,000の1.1倍に
  ぴったり乗ることが根拠。保留リストに書き残してある。

--- 計上月 ----------------------------------------------------------------
【入金月】をそのままPLの列にした。9月〜4月に1件ずつきれいに並ぶ。
請求書が無いので請求月が分からず、月ズレを当てる根拠が無い。

--- いつ終わったか --------------------------------------------------------
2026/04/30 が最後で、5月以降は入っていない。同じ時期に
2026/05/14 の 66,002円の返金（地域活性舎への出金）もあるので、
このあたりで事務代行の関係が終わったとみられる。5月〜8月が空くのはこのため。
"""
import collections

import bank

TAB = "本部"
PLROW = "その他売上"
RATE = 10                       # 事務代行は課税役務。33,000＝30,000×1.1
INC = 33000                     # 1件あたりの税込
EX = INC * 100 // (100 + RATE)  # 30,000

SRC = "bank/小見川支店_普通_3351509_YYYYMM.csv"

# (入金日, PL列)。入金月をそのまま列にする
DEPOSITS = [
    ("2025/09/26", "9月"),  ("2025/10/31", "10月"),
    ("2025/11/25", "11月"), ("2025/12/25", "12月"),
    ("2026/01/27", "1月"),  ("2026/02/25", "2月"),
    ("2026/03/26", "3月"),  ("2026/04/30", "4月"),
]

NOTE = ("地域活性舎からの事務代行手数料（利用者確認 2026-09-03"
        "「これは事務手数料、事務代行してたので」）。千葉銀行3351509への"
        "毎月33,000円の定額入金。33,000＝30,000×1.1 なので10%課税とみて"
        "税抜30,000＋消費税3,000。boardにも売掛にも請求書が無く、"
        "記録は銀行明細だけ。計上月は入金月")


def _bank():
    """{入金日: 金額}。本体口座の地域活性舎からの入金を銀行明細から引き直す"""
    d = collections.Counter()
    for date, raw, amt, internal, _src in bank.deposits("3351509"):
        if "チイキカツセイシヤ" in raw:
            d[date] += amt
    return d


def rows():
    """(タブ, PL行, 月, 税抜, 元ファイル, メモ) を列挙。"""
    for date, m in DEPOSITS:
        yield (TAB, PLROW, m, EX, SRC, f"{NOTE}（入金 {date} {INC:,}円）")


def check(wb=None):
    """銀行明細に実際にその入金があるか／取りこぼしが無いか／書き込み先が空か。"""
    idx = _bank()
    for date, m in DEPOSITS:
        assert idx.get(date) == INC, \
            f"{m}: 銀行明細の {date} が {idx.get(date)}（想定 {INC:,}）"
    # ★入金を取りこぼしていないこと。新しい月の明細を足したらここで止まる
    assert len(idx) == len(DEPOSITS), \
        (f"地域活性舎からの入金が銀行に {len(idx)} 件ある（想定 {len(DEPOSITS)} 件）。"
         f"明細が増えたらここを見直すこと: {sorted(idx)}")
    assert EX + EX * RATE // 100 == INC, "税抜＋10% ≠ 33,000"
    if wb is None:
        return
    import build2
    assert PLROW in build2.RIDX[TAB], f"{TAB} に「{PLROW}」行が無い"
    for _date, m in DEPOSITS:
        c = wb[TAB][f"{build2.MCOL[m]}{build2.RIDX[TAB][PLROW]}"]
        assert not c.value, (f"{TAB} {PLROW} {m} に既に {c.value} が入っている。"
                             f"{EX:,} を足すと二重計上になる")


def hold_rows():
    """計上はしたが根拠が弱いところ。記録として保留リストに残す。"""
    return [
        ("9月〜4月", TAB, PLROW,
         f"地域活性舎からの事務代行手数料 33,000円×8件＝264,000円（税込）を、"
         f"本部「その他売上」に税抜30,000円ずつ入れた（利用者指示 2026-09-03"
         f"「本部のその他売上で」）。"
         f"★請求書がboardにも売掛フォルダにも無い。記録は銀行の入金だけなので、"
         f"(1)税率10%は 33,000＝30,000×1.1 からの推定、"
         f"(2)計上月は入金月をそのまま使っている（請求月が分からないため）。"
         f"2026/05以降は入金が無く、2026/05/14に66,002円を返金しているので、"
         f"このあたりで事務代行が終わったとみられる"),
    ]


if __name__ == "__main__":
    check()
    for tab, plrow, m, val, src, _note in rows():
        print(f"{tab:<6} {plrow:<8} {m:>3}  {val:>8,}")
    print(f"\n計 {sum(r[3] for r in rows()):,}円（税抜）／"
          f"消費税 {INC * len(DEPOSITS) - sum(r[3] for r in rows()):,}円／"
          f"税込 {INC * len(DEPOSITS):,}円")
    print("検算すべて通過")
