"""カード決済（カメイ・テン・サービス）の加盟店手数料 → 鳥害対策課

--- 元データ -------------------------------------------------------------
Dropbox /※請求書※/銀行明細/21期/お支払計算書_YYYYMMDDhhmmss.csv
    UTF-8（BOMつき）。1ファイル＝1回の精算。中身は2段組み。
      1段目（1〜2行目）… 締日・支払日・振込口座・売上金額合計・加盟店手数料合計・
                          今回支払金額合計
      2段目（3行目以降）… 取扱（国内Visa／国内Master）・お支払方法・加盟店手数料率・
                          今回売上件数・今回売上金額（a）…
    ローカルには kamei/<締日>.csv として置いてある（ファイル名が時刻で区別できないため）。

    加盟店番号は8件とも 100000000009927、振込先は千葉銀行 小見川支店 普通 3351509
    （本体口座）、名義 ﾌﾟﾛｽﾀｲﾙｶﾌﾞｼｷｶﾞｲｼｬ。手数料率はぜんぶ 3.25%。

--- 銀行明細と突き合わせ済み --------------------------------------------
8件とも本体口座(3351509)に「カメイテンサービス」名義で1円まで一致して入金がある。
    2026/01/09 180,923 ／ 02/27 106,425 ／ 03/19 53,213 ／ 04/10 53,213
    04/30 53,213 ／ 06/10 53,213 ／ 07/17 117,068 ／ 08/20 42,570

--- ★どの月に入れるか（締日の月）--------------------------------------
このシステムは「お金が動いた月」ではなく「取引が起きた月」に入れる作りなので、
手数料も【締日の月】に入れている。売上（board売掛）と同じ月に手数料が並ぶ。
    締日 2026/07/10 の 121,000 は board の請求No.8136（飯田栄・2026年07月分請求・
    鳥害対策課・121,000）と一致 → 7月
    締日 2026/08/10 の  44,000 は board の請求No.8249（支柱ネット本工・クレジット・
    鳥害対策課・44,000）と一致 → 8月
入金日（支払日）の月で入れると 12月→1月・3月→4月・5月→6月 の3件がずれる。
入金日基準にしたい場合は BASIS を "支払日" に変えれば切り替わる。

--- 売上は二重計上していない -------------------------------------------
売上は board の売掛CSV（請求ベース）から入っている。この精算書の「売上金額」は
その請求をカードで回収したというだけなので、PLには手数料しか入れない。

--- ★消費税 ------------------------------------------------------------
クレジットカードの加盟店手数料は【非課税】（金銭債権の譲渡等）なので、
消費税は切り出さず、手数料の額をそのまま入れている。
"""
import csv
import glob
import os

BASE = os.path.dirname(os.path.abspath(__file__))
DIR = os.path.join(BASE, "kamei")

TAB = "鳥害対策課"
ROW = "支払手数料（クレジット決済）"

# "締日" … 取引が起きた月（既定）／"支払日" … 入金があった月
BASIS = "締日"

# 決算期の並び。YYYYMM -> PL列
YM2M = {"202509": "9月", "202510": "10月", "202511": "11月", "202512": "12月",
        "202601": "1月", "202602": "2月", "202603": "3月", "202604": "4月",
        "202605": "5月", "202606": "6月", "202607": "7月", "202608": "8月"}

# 銀行明細（本体口座 3351509）で確かめた入金。支払日 -> (入金額, 摘要)
BANK = {
    "20260109": (180923, "カメイテンサ−ビス"),
    "20260227": (106425, "カメイテンサ－ビス"),
    "20260319": (53213,  "カメイテンサ－ビス"),
    "20260410": (53213,  "カメイテンサ－ビス"),
    "20260430": (53213,  "カメイテンサ−ビス"),
    "20260610": (53213,  "カメイテンサ−ビス"),
    "20260717": (117068, "カメイテンサ－ビス"),
    "20260820": (42570,  "カメイテンサ−ビス"),
}

# board売掛と突き合わせがついたもの。締日 -> (請求No, 案件名)
BOARD = {
    "20260710": ("8136", "2026年07月分請求（飯田栄）"),
    "20260810": ("8249", "支柱ネット本工（クレジット）"),
}


def _read(path):
    """1ファイル → dict"""
    rows = list(csv.reader(open(path, encoding="utf-8-sig")))
    head = dict(zip(rows[0], rows[1]))
    detail = [dict(zip(rows[2], r)) for r in rows[3:] if r]
    return {
        "締日":   head["締日"],
        "支払日": head["支払日"],
        "売上":   int(head["売上金額合計"]),
        "手数料": int(head["加盟店手数料合計"]),
        "入金":   int(head["今回支払金額合計"]),
        "加盟店": head["加盟店番号"],
        "口座":   head["振込口座番号"],
        "取扱":   "・".join(sorted({d["取扱"] for d in detail})),
        "料率":   "・".join(sorted({d["加盟店手数料率"] for d in detail})),
        "件数":   sum(int(d["今回売上件数"]) for d in detail),
        "src":    "銀行明細/21期/お支払計算書（カメイ・テン・サービス）"
                  f" 締日{head['締日']}",
    }


def entries():
    """精算書を締日の順に並べて返す"""
    out = [_read(p) for p in sorted(glob.glob(os.path.join(DIR, "*.csv")))]
    return sorted(out, key=lambda d: d["締日"])


def _month(d):
    key = d["締日"] if BASIS == "締日" else d["支払日"]
    return YM2M[key[:6]]


def rows():
    """(タブ, PL行, 月, 金額, 元ファイル, メモ) を列挙。同じ月は足し合わせる。"""
    by = {}
    for d in entries():
        m = _month(d)
        by.setdefault(m, []).append(d)
    for m, ds in by.items():
        total = sum(d["手数料"] for d in ds)
        note = "／".join(
            f"締日{d['締日']} 売上{d['売上']:,}×{d['料率']}%＝手数料{d['手数料']:,}"
            f"（{d['取扱']}・{d['件数']}件、{d['支払日'][:4]}/{d['支払日'][4:6]}/"
            f"{d['支払日'][6:]}に本体口座へ{d['入金']:,}入金）"
            + (f"。board請求No.{BOARD[d['締日']][0]} {BOARD[d['締日']][1]} と一致"
               if d["締日"] in BOARD else "")
            for d in ds)
        yield (TAB, ROW, m, total, ds[0]["src"],
               "カード決済の加盟店手数料（非課税）。" + note
               + f"。計上月は【{BASIS}】の月")


def check(wb=None):
    """精算書そのものの整合と、銀行明細との一致を確かめる"""
    for d in entries():
        assert d["売上"] - d["手数料"] == d["入金"], (
            f"締日{d['締日']}: 売上{d['売上']:,}−手数料{d['手数料']:,}"
            f"≠入金{d['入金']:,}")
        assert d["口座"] == "3351509", f"締日{d['締日']}: 振込先が本体口座でない"
        got = BANK.get(d["支払日"])
        assert got, f"支払日{d['支払日']} の入金が銀行明細の控えに無い"
        assert got[0] == d["入金"], (
            f"支払日{d['支払日']}: 精算書{d['入金']:,} ≠ 銀行明細{got[0]:,}")
    if wb is None:
        return
    import build2
    assert ROW in build2.RIDX[TAB], f"{TAB} に「{ROW}」行が無い"
    for tab, plrow, m, v, _s, _n in rows():
        c = wb[tab][f"{build2.MCOL[m]}{build2.RIDX[tab][plrow]}"]
        assert not c.value, (f"{tab} {plrow} {m} に既に {c.value} が入っている。"
                             f"手数料の {v:,} を足すと二重計上になる")


