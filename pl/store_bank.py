def _ex(inc, rate):
    """引落（税込）から課税税抜Xを逆算。X + floor(X*rate/100) == inc なるX。
    見つからなければ floor(inc*100/(100+rate)) に落とす。"""
    base = inc * 100 // (100 + rate)
    for x in (base - 1, base, base + 1, base + 2):
        if x + x * rate // 100 == inc:
            return x, True
    return base, False


def _debits():
    """{(口座, 摘要): {年月: 引落合計}}。同じ行を2回数えない。"""
    d = collections.defaultdict(lambda: collections.defaultdict(int))
    seen = set()
    accounts = {a for a, _ in VENDORS}
    for path in sorted(glob.glob(os.path.join(DIR, "*小見川支店*.csv"))):
        acct = os.path.basename(path).split("_")[2]
        if acct not in accounts:
            continue
        for r in csv.DictReader(open(path, encoding="utf-8-sig")):
            if not r["出金金額(円)"]:
                continue
            key = (acct, r["取引日"], r["摘要"], r["出金金額(円)"], r["残高(円)"])
            if key in seen:
                continue
            seen.add(key)
            k = (acct, r["摘要"].strip())
            if k in VENDORS:
                d[k][r["取引日"].replace("/", "")[:6]] += int(r["出金金額(円)"])
    return d


def _bank_ym(month, lag):
    i = _ORDER.index(YM[month]) + lag
    return _ORDER[i] if i < len(_ORDER) else None


def rows(wb=None):
    """(タブ, PL行, 月, 税抜, 元ファイル, メモ) を列挙。
    請求書から既に入っている取引先・月は飛ばす。"""
    d = _debits()
    for (acct, raw), (tab, plrow, lag, rate, name) in sorted(
            VENDORS.items(), key=lambda x: (x[1][0], x[1][1])):
        for m in MONTHS:
            if (acct, raw, m) in FROM_INVOICE:
                continue
            ym = _bank_ym(m, lag)
            if ym is None or ym not in d[(acct, raw)]:
                continue
            inc = d[(acct, raw)][ym]
            ex, exact = _ex(inc, rate)
            yield (tab, plrow, m, ex,
                   f"銀行明細/21期/小見川支店_普通_{acct}_{ym}*.csv",
                   f"{name}。引落{inc:,}（税込{rate}%）→ 税抜{ex:,}"
                   + ("" if exact else "。端数が割り切れず切り捨て"))


def skipped():
    """請求書と重なって飛ばした (タブ, PL行, 月, 請求書の額, 銀行から逆算した額)"""
    d = _debits()
    for (acct, raw), (tab, plrow, lag, rate, name) in VENDORS.items():
        for m in MONTHS:
            if (acct, raw, m) not in FROM_INVOICE:
                continue
            ym = _bank_ym(m, lag)
            if ym is None or ym not in d[(acct, raw)]:
                continue
            ex, _ = _ex(d[(acct, raw)][ym], rate)
            yield tab, plrow, m, FROM_INVOICE[(acct, raw, m)], ex


def hold_rows():
    """入れなかったものと、目立つ月・埋まらない月を保留リストへ"""
    import statistics
    d = _debits()
    for (acct, raw), (tab, plrow, lag, rate, name) in sorted(
            VENDORS.items(), key=lambda x: (x[1][0], x[1][1])):
        got = {m: d[(acct, raw)][_bank_ym(m, lag)]
               for m in MONTHS
               if _bank_ym(m, lag) and _bank_ym(m, lag) in d[(acct, raw)]}
        if not got:
            continue
        # ★他の月から飛び抜けている月。まとめ払いか別件の可能性がある
        med = statistics.median(got.values())
        for m, v in sorted(got.items(), key=lambda x: MONTHS.index(x[0])):
            if v > med * 3:
                ex, _ = _ex(v, rate)
                yield (m, tab, plrow,
                       f"{name}の引落が {v:,}円（税込）で、他の月の中央値 {med:,.0f}円の"
                       f"{v/med:.0f}倍ある。税抜 {ex:,}円として計上したが、"
                       f"数か月ぶんのまとめ払いか別件が混じっている可能性がある")
        # 引落も請求書も無い月
        miss = [m for m in MONTHS
                if m not in got and (acct, raw, m) not in FROM_INVOICE]
        if miss:
            yield ("・".join(miss), tab, plrow,
                   f"{name}。この月は引落が見つからず請求書も無いので空欄のまま。"
                   f"引落日が明細の期間外か、翌月にまとめて落ちている可能性")
    for tab, name, amount, why in NOT_POSTED:
        yield ("通年", tab, name, f"{amount:,}円（税込）。{why}")


def check(wb=None):
    """逆算と月ズレが正しいことを、既存PLシートと請求書で確かめる"""
    d = _debits()
    # ① 焼きたて屋のガス代が既存PLと11か月とも合うこと
    for m in MONTHS:
        ym = _bank_ym(m, 1)
        if ym is None or ym not in d[("3543939", "ガスリヨウキン")]:
            continue
        ex, _ = _ex(d[("3543939", "ガスリヨウキン")][ym], 10)
        want = EXIST_YAKITATE_GAS[m]
        assert abs(ex - want) <= 1, \
            f"焼きたて屋ガス {m}: 逆算 {ex:,} ≠ 既存PL {want:,}"
    # ② 請求書と重なる月が一致すること
    #   重なるのは6月だけ。7月ぶんの引落は2026/08で、店舗口座の明細は
    #   2026/07までしか無いため照合できない（神栖横丁の口座だけ8月がある）。
    #   鈴喜は8%と10%が混じった請求なので逆算が±2円ずれる。想定内。
    bad = [x for x in skipped() if abs(x[3] - x[4]) > 3]
    good = sum(1 for x in skipped() if abs(x[3] - x[4]) <= 1)
    assert good >= 5, f"請求書と1円まで合った月が {good} しかない。月ズレか逆算が違う"
    return bad


