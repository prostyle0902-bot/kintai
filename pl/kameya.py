#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""かめや（焼きたて屋のFC本部）からの月次書類 → 焼きたて屋タブ

焼きたて屋の数字は、ほぼ全部がこの3点セットから来ている。
Dropboxの請求書フォルダにある 門倉石油（ガス）・丸善エコアース（ごみ）・
鹿島食品（仕入）を除くと、残りは全部かめや。

--- 毎月かめやから届く3ファイル -----------------------------------------
  ① YYYY.M 合計精算書.pdf      … 売上とロイヤリティ、差引支払額
  ② YYYY.M 合計請求書.pdf      … 家賃・POSレジ・現金輸送など経費の明細
  ③ YYYY.Mインフォマート請求書.pdf … 食材仕入（8%/10%の内訳つき）

★2026-08-20 時点で、21期（2025.09〜2026.07）のこの3ファイルは
  Dropboxにも Googleドライブにも1つも入っていない。
  Dropbox全体を検索して見つかった「合計精算書」は31件、最新が 2025.5 で、
  置き場所は個人領域の
      /My Mac (SakaenoMacBook-Pro.local)/Downloads/2025年/
      /My Mac (…)/Downloads/2025年/焼きたて屋20期/YYYY.M月/
      /精算書 (選択型同期の競合)/35期/   ・   /Prostyle株式会社 (1)/精算書/35期/
  かめや名義の請求書は /※請求書※/買掛/ の 17期・19期 にしかない。
  → DATA が空なのはそのため。ファイルが入り次第うめる。

  置き場所の提案（既存の並びに合わせる）:
      /※請求書※/買掛/21期/26MM月/焼きたて屋/かめや　合計精算書.pdf
                                          /かめや　合計請求書.pdf
                                          /かめや　インフォマート請求書.pdf

--- ①合計精算書の読み方 -------------------------------------------------
「【コメリパワー鹿嶋店】POS売上明細表」に日別で 税抜売上／消費税／税込金額。
最下行の「計」が月計。右側に控除の計算がある。

    売上（税込）  ← 月計の「税込金額」
    消費税        ← 月計の「消費税」   ★日別の合計なので 8%/10% 混在が反映済み
    ロイヤリティ  ← 「ロイヤリティ（税抜売上5％）」

★既存PLの消費税の正体（2026-08-20 判明）
  yakitateya.py に「既存PLの計算根拠は不明」と書いてあったが、根拠はこれ。
  既存PLの消費税は、かめや精算書の日別消費税の合計をそのまま写したもの。
  だから 売上集計表に方法A（月計から 8/108・10/110 で逆算）を当てると
  数百円ずれる。日別合計のほうが実態に近いので、22期は精算書の値を使う。

--- ②合計請求書の読み方 -------------------------------------------------
伝票ごとに品名と税抜金額が並ぶ。毎月かならず出る定額分（FIXED）と、
月によって出たり出なかったりする変動分がある。

--- ③インフォマート請求書の読み方 ---------------------------------------
表紙1枚に「10%対象／8%対象」の金額・消費税・請求金額。金額（税抜）を使う。
    仕入（インフォマート10％） ← 10%対象の金額
    仕入（インフォマート8％）  ← 8%対象の金額

--- 突き合わせ済み（2026-08-20）-----------------------------------------
実物のPDFを開いて、既存PLスプシと1円まで一致することを確認した。
  20期 5月  精算書 税抜売上 1,431,519  → PL 売上 1,431,519           ✅
  20期 5月  精算書 ロイヤリティ 71,576 → PL ロイヤリティ 71,576      ✅
  20期12月  インフォマート 641,295     → PL 仕入（本部）641,295      ✅
  20期12月  合計請求書 税抜 193,952    → PL 本部支払い経費 193,952   ✅
  20期 7月  FIXED合計 180,500 + 振込手数料39 = 180,539
                                        → PL 本部支払い経費 180,539  ✅
  21期      ロイヤリティ = round(税抜売上 × 5%) が11か月とも一致       ✅
            （切り捨てだと4か月ずれる。かめやは四捨五入）

20期のPLは「仕入（本部）」「本部支払い経費」と大づかみだったが、
21期のPLは費目ごとに行が割ってある。下の ITEM2ROW がその対応。
"""
from decimal import Decimal, ROUND_HALF_UP

TAB = "焼きたて屋"

# ②合計請求書の品名 → 21期PLの行名
ITEM2ROW = {
    "賃料":                 "地代家賃（賃料）",
    "駐車場代":             "地代家賃（駐車場利用料）",
    "ユニットハウス置場代":   "地代家賃（裏プレハブ賃料）",
    "電気料金":             "水道光熱費（電気料金）",
    "水道料金":             "水道光熱費（水道料金）",
    "POSレジ使用料":         "通信費（POSレジ）",
    "機器賃貸料":           "通信費（POSレジ利用料）",
    "現金輸送業務":          "外注費（現金輸送費）",
    "家賃/振込手数料":       "支払手数料（かめや）",
}

# 毎月かならず出る定額分（税抜）。21期の既存PLも11か月ぜんぶこの額だった。
FIXED = {
    "賃料":               120000,
    "駐車場代":             4500,
    "ユニットハウス置場代":   3000,
    "電気料金":            10000,
    "水道料金":             3000,
    "POSレジ使用料":       10000,
    "機器賃貸料":           6000,
    "現金輸送業務":         24000,
}
FIXED_TOTAL = sum(FIXED.values())          # 180,500

# 変動分。金額が毎月ちがうので、請求書を読んでから入れる。
#   販促品（のぼり・チラシ・ハッピーセット等） → 広告宣伝費（共通宣伝費）
#   衛生関係（害虫駆除など）                 → 保険衛生費
VARIABLE_HINT = {
    "販促品":   "広告宣伝費（共通宣伝費）",
    "衛生":     "保険衛生費",
}

# ★行き先が決まっていないもの → 保留リストに出す。推測で入れない。
UNASSIGNED = {
    "Paypay手数料":
        "20期（〜2025.8頃）はかめや経由で請求されていた（例: 2024.12 ¥2,573）。"
        "21期のPLには対応する行がなく、支払手数料（Softbank）が別系統で入っている。"
        "21期の請求書に載っていたらどの行に入れるか要指示。",
}

# 月 -> 各値。21期のファイルが手に入り次第うめる。22期は最初から使う。
#   {"9月": {"売上税込":…, "消費税":…, "ロイヤリティ":…,
#            "インフォマート10":…, "インフォマート8":…,
#            "経費": {"賃料":120000, …}, "src": "…"}}
DATA = {}

# --- 21期の既存PL実測値（検算用。ここから転記はしない）-------------------
# file_id 1OB3yLta9y1d14DbN3jeqCoL9MKFknUbBnqR1WBOvLYQ  2026-08-20 読み取り
MONTHS_21 = ["9月","10月","11月","12月","1月","2月","3月","4月","5月","6月","7月"]
EXIST_21 = {
    "売上（税込）": [1045825,1280545,1308390,1484135,1527320,1334680,1583615,
                 1358985,1354610,1150880,1082165],
    "消費税":     [77925,95420,97578,110633,113888,99551,118078,101343,101004,
                 85802,80661],
    "ロイヤリティ": [48395,59256,60541,68675,70672,61756,73277,62882,62680,53254,50075],
    "仕入（インフォマート10％）": [81412,36919,64374,61279,52513,34477,57224,52806,
                            9910,60400,46354],
    "仕入（インフォマート8％）":  [329788,364672,299775,376400,397794,324380,238034,
                            329808,322631,262212,297929],
}


def royalty(ex_sales):
    """ロイヤリティ = 税抜売上 × 5%（四捨五入）。21期11か月で検証済み。"""
    return int((Decimal(ex_sales) * 5 / 100).to_integral_value(ROUND_HALF_UP))


def rows():
    """(タブ, PL行, 月, 金額, 元ファイル) を列挙。DATAが空なら何も返さない。"""
    for m, d in DATA.items():
        src = d.get("src", "かめや")
        yield TAB, "売上（税込）", m, d["売上税込"], src
        yield TAB, "消費税", m, d["消費税"], src
        yield TAB, "ロイヤリティ", m, d["ロイヤリティ"], src
        yield TAB, "仕入（インフォマート10％）", m, d["インフォマート10"], src
        yield TAB, "仕入（インフォマート8％）", m, d["インフォマート8"], src
        for item, amount in d.get("経費", {}).items():
            plrow = ITEM2ROW.get(item) or VARIABLE_HINT.get(item)
            if plrow is None:
                continue          # 行き先未定 → hold_rows() が拾う
            yield TAB, plrow, m, amount, src


def hold_rows():
    """保留: 21期のファイルが無いこと＋行き先未定の費目"""
    if not DATA:
        yield ("21期全月", "かめや 合計精算書・合計請求書・インフォマート請求書",
               "Dropbox/Driveのどちらにも21期分（2025.09〜2026.07）が無い。"
               "見つかった最新は個人領域の 2025.5。ファイルを "
               "/※請求書※/買掛/21期/26MM月/焼きたて屋/ に入れてもらえれば取り込む。"
               "対象行: 売上（税込）／消費税／ロイヤリティ／仕入（インフォマート8％・10％）"
               "／地代家賃3行／水道光熱費2行／通信費（POSレジ・POSレジ利用料）"
               "／外注費（現金輸送費）／支払手数料（かめや）／広告宣伝費／保険衛生費")
    for m, d in DATA.items():
        for item, amount in d.get("経費", {}).items():
            if item in UNASSIGNED:
                yield (m, item, UNASSIGNED[item] + f"（{amount:,}円）")


def check():
    """ロイヤリティの計算式が既存PLと合うことを確認する"""
    for i, m in enumerate(MONTHS_21):
        ex = EXIST_21["売上（税込）"][i] - EXIST_21["消費税"][i]
        got, want = royalty(ex), EXIST_21["ロイヤリティ"][i]
        assert got == want, f"{m}: ロイヤリティ {got:,} ≠ 既存PL {want:,}"
    return True


if __name__ == "__main__":
    check()
    print("ロイヤリティ = round(税抜売上×5%) は21期11か月とも既存PLと一致 ✅\n")
    print(f"毎月の定額経費 FIXED 合計 {FIXED_TOTAL:,}円")
    for item, v in FIXED.items():
        print(f"  {item:<22} {v:>8,}  → {ITEM2ROW[item]}")
    print(f"\n21期の取り込み対象: {len(DATA)}か月ぶん")
    for x in hold_rows():
        print("\n保留:", x[0], "／", x[1])
