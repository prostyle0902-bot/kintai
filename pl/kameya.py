def check():
    """PDFから起こした値が既存PLと合うことを確認する。差があれば返す。

    ロイヤリティの式・経費合計＝請求書の税抜御買上額・各行の既存PL一致、の3本。
    KNOWN_DIFF に入っている差は想定内として無視する。
    """
    for i, m in enumerate(MONTHS_21):
        ex = EXIST_21["売上（税込）"][i] - EXIST_21["消費税"][i]
        got, want = royalty(ex), EXIST_21["ロイヤリティ"][i]
        assert got == want, f"{m}: ロイヤリティ {got:,} ≠ 既存PL {want:,}"

    for m, d in DATA.items():
        got = sum(d["経費"].values())
        want = INVOICE_TOTAL[m]
        assert got == want, f"{m}: 経費合計 {got:,} ≠ 請求書の税抜御買上額 {want:,}"

    diffs = []
    by_row = {}
    for tab, plrow, m, val, src in rows():
        by_row.setdefault(plrow, {})[m] = val
    for plrow, vals in EXIST_21.items():
        for i, m in enumerate(MONTHS_21):
            want, got = vals[i], by_row.get(plrow, {}).get(m, 0)
            if want is None or (m, plrow) in KNOWN_DIFF:
                continue
            assert got == want, f"{m} {plrow}: PDF {got:,} ≠ 既存PL {want:,}"
    for m, plrow in sorted(KNOWN_DIFF):
        i = MONTHS_21.index(m)
        diffs.append((m, plrow, EXIST_21[plrow][i], by_row.get(plrow, {}).get(m, 0)))
    return diffs


