def classify(filename):
    """ファイル名から3種類のどれかを判定する。判定できなければ None。

    ★順番が大事。「合計請求書」も「インフォマート請求書」も『請求書』を含むので、
      インフォマート → 精算書 → 請求書 の順に見る。
    """
    if "インフォマート" in filename:
        return "インフォマート請求書"
    if "精算書" in filename:
        return "合計精算書"
    if "請求書" in filename:
        return "合計請求書"
    return None


