#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""本部の「諸会費」

会費類の受け皿として2026-08-20に新設した行（利用者指示）。
    「本部に諸会費ってないね。諸会費作って、エクセレントリーダーはそこに入れようか。
      今後のロータリーも。」

--- ここに入れるもの ----------------------------------------------------
・エクセレントリーダーズ（EL会費）
・ロータリークラブ  ★今後ぶんだけ。21期の既存分は触らない（下記）
・そのほか会費と名のつくもの

--- ロータリークラブについての注意 --------------------------------------
本部タブには以前からある「ロータリークラブ」行（売上原価セクション）に
91,000円が入っている。21期はそのまま。22期以降のロータリー会費を
この諸会費に入れる。

★ついでに見つかった相違（未対応）:
  既存スプシは 2月に91,000、新シートは請求書（2606月フォルダ）から6月に91,000。
  年計は同じだが計上月が違う。どちらが正か未確認。

--- 消費税 --------------------------------------------------------------
PLは税抜なので、請求書の税抜額を入れる。
"""

TAB = "本部"
ROW = "諸会費"

# (月, 取引先, 税抜, 元ファイル, メモ)
DATA = [
    ("7月", "一般社団法人Excellent Leaders", 10000,
     "買掛/21期/2607月/本部/支払い済/エクセレントリーダーズ.pdf",
     "EL会費 2026.7月分。請求書は@10,000×2件で7月・8月の2か月分（税抜計20,000／"
     "税込22,000）。1か月ずつ発生した月に分けた"),
    ("8月", "一般社団法人Excellent Leaders", 10000,
     "買掛/21期/2607月/本部/支払い済/エクセレントリーダーズ.pdf",
     "EL会費 2026.8月分。同上"),
]

# 請求書の検算値（税抜, 消費税, 税込）
CHECK = {"一般社団法人Excellent Leaders": (20000, 2000, 22000)}

# 請求書に残る気になる点。金額は確定なので転記はするが、メモとして残す。
NOTES = [
    "エクセレントリーダーズの請求書は宛名が『飯田 栄 様』個人宛（法人宛ではない）",
    "同・登録番号が空欄。インボイス（適格請求書）ではないので仕入税額控除は不可",
]


def rows():
    """(タブ, PL行, 月, 税抜, 元ファイル, メモ) を列挙。"""
    for month, vendor, ex, src, note in DATA:
        yield TAB, ROW, month, ex, src, f"{vendor} — {note}"


def check():
    """取引先ごとの合計が請求書の税抜額と合うことを確認する"""
    by = {}
    for month, vendor, ex, src, note in DATA:
        by[vendor] = by.get(vendor, 0) + ex
    for vendor, (ex, tax, inc) in CHECK.items():
        got = by.get(vendor, 0)
        assert got == ex, f"{vendor}: 明細計 {got:,} ≠ 請求書の税抜 {ex:,}"
        assert ex + tax == inc, f"{vendor}: 税抜{ex:,}+税{tax:,} ≠ 税込{inc:,}"
    return True


if __name__ == "__main__":
    check()
    print(f"{TAB} / {ROW}\n")
    for tab, row, m, ex, src, note in rows():
        print(f"  {m:<4} {ex:>8,}  {note}")
    print(f"  {'計':<4} {sum(d[2] for d in DATA):>8,}")
    print("\nメモ:")
    for n in NOTES:
        print("  -", n)
