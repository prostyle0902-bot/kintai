def _read(path):
    for enc in ("utf-8-sig", "cp932"):
        try:
            with open(path, encoding=enc) as f:
                return list(csv.DictReader(f))
        except UnicodeDecodeError:
            continue
    raise RuntimeError(path)


def _union(pattern, key):
    """パターンに当たるCSVを全部読んで、主キー列で重複を落とす。
    後から読んだファイルで上書きする（新しいエクスポートを優先）。

    ★主キーはファイルの種類ごとに違う（FILES の3つめ）。8月の案件エクスポートを
      「合計請求書No」で落とすと、1つの合計請求書にぶら下がる複数の請求書が
      消えてしまう（実際に12件が重複していて23行が消えた）。"""
    merged = {}
    for path in sorted(glob.glob(os.path.join(DIR, pattern))):
        rows = _read(path)
        assert rows and key in rows[0], f"{os.path.basename(path)} に「{key}」列が無い"
        for r in rows:
            merged[r[key]] = r
    return list(merged.values())


def _supplement(month):
    """その月の「足りないぶんだけ補う」行を返す。(行, 書き込み先) の組。

    相手のファイルに同じ合計請求書Noがあるものは採らない（二重計上になるため）。
    """
    out = []
    for name, m, key, against, dest in SUPPLEMENT:
        if m != month:
            continue
        have = {r.get("合計請求書No", "") for r in _union(against, "請求書ID")}
        for r in _union(name, key):
            no = r.get(key, "")
            if no and no in have:
                continue
            out.append((r, dest))
    return out


def _group(r):
    """グループ列。空なら GROUP_OVERRIDE（利用者指示）で埋める。"""
    g = r.get("グループ") or ""
    if not g:
        ov = GROUP_OVERRIDE.get(r.get("請求書No", ""))
        if ov:
            return ov[0]
        cust = r.get("顧客名") or ""
        for kw, grp in GROUP_BY_CUSTOMER:
            if kw in cust:
                return grp
    return g


