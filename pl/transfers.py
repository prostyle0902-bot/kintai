def _ex(inc, rate):
    """振込額（税込）から税抜Xを逆算。X + floor(X*rate/100) == inc なるX。"""
    base = inc * 100 // (100 + rate)
    for x in (base - 1, base, base + 1, base + 2):
        if x + x * rate // 100 == inc:
            return x, True
    return base, False


def _lag(day):
    """支払日の日にち → 何か月前の請求分か。冒頭の★の実測による。"""
    return 1 if day >= 20 else 2


def _paid():
    """{摘要の一部: {計上月(YYYYMM): 税込合計}}。千葉銀行の店舗口座＋PayPay。"""
    out = collections.defaultdict(lambda: collections.defaultdict(int))
    for date, bk, raw, _v, amount, _src, _known in bank.payments():
        for frag, (_t, _r, _rate, _name, chiba, _memo) in VENDORS.items():
            if frag not in raw:
                continue
            if bk.startswith("千葉銀行") and bk != chiba:
                continue          # 本体口座や他店の口座の同名支払いは拾わない
            y, m, d = (int(x) for x in date.split("/"))
            i = _ORDER.index(f"{y}{m:02d}") - _lag(d)
            if 0 <= i < len(_ORDER):
                out[frag][_ORDER[i]] += amount
            break
    return out


def rows(wb=None):
    """(タブ, PL行, 月, 税抜, 元ファイル, メモ) を列挙"""
    paid = _paid()
    for frag, (tab, plrow, rate, name, chiba, memo) in sorted(
            VENDORS.items(), key=lambda x: (x[1][0], x[1][1])):
        for m in MONTHS:
            if (frag, m) in FROM_INVOICE or YM[m] not in paid[frag]:
                continue
            inc = paid[frag][YM[m]]
            ex, exact = _ex(inc, rate)
            yield (tab, plrow, m, ex, "銀行明細/21期/（千葉銀行の店舗口座＋PayPay銀行）",
                   f"{name}。振込{inc:,}（税込{rate}%）→ 税抜{ex:,}"
                   + ("" if exact else "。端数が割り切れず切り捨て")
                   + (f"。{memo}" if memo else ""))


def hold_rows():
    """入れなかったものを保留リストへ"""
    for tab, name, amount, why in NOT_POSTED:
        yield ("通年", tab, name, f"{amount:,}円（税込）。{why}")


def check(wb=None):
    """月ズレの決め方が正しいことを、既存PLシートで確かめる"""
    paid = _paid()
    hit = 0
    for m, want in EXIST_YAKITATE_GOMI.items():
        if want is None or YM[m] not in paid["マルゼン"]:
            continue
        ex, _ = _ex(paid["マルゼン"][YM[m]], 10)
        if (("マルゼン", m) not in FROM_INVOICE) and ex == want:
            hit += 1
    assert hit >= 6, \
        f"丸善エコアースが既存PLと合った月が {hit} しかない。月ズレの決め方が違う"
    return []


