def rows():
    """(タブ, PL行, 月, 税抜金額, 元ファイル) を列挙。店舗側の費用だけ。"""
    for month, stores in DATA.items():
        for tab, d in stores.items():
            by_row = {}
            for item, amount in d.items():
                plrow = ITEM2ROW.get(item)
                if plrow is None:
                    continue        # 小計・税込・No・src はここでは出さない
                by_row[plrow] = by_row.get(plrow, 0) + amount
            for plrow, amount in by_row.items():
                yield tab, plrow, month, amount, d["src"]


def hold_rows():
    """保留: 神栖横丁側の売上と、相殺・値引き"""
    for month, stores in DATA.items():
        total = sum(d["小計"] for d in stores.values())
        yield (month, TAB_OWNER, "テナント請求（売上）",
               f"3店舗ぶん税抜 {total:,}円を読み取ったが、神栖横丁の売上は"
               f"9月〜6月が毎月220万〜252万。テナントは3店舗だけではなく、"
               f"残りの合計請求書がDropboxに無い。一部だけ入れると売上が実態と"
               f"かけ離れるため未計上。全店ぶんが揃ったら入れる。")
        for tab, d in stores.items():
            for item, amount in d.items():
                if item in UNASSIGNED:
                    yield (month, tab, item,
                           UNASSIGNED[item] + f"（{amount:,}円）")


def check():
    """明細の合計が請求書の小計・税込と合うことを確認する"""
    for month, stores in DATA.items():
        for tab, d in stores.items():
            got = sum(v for k, v in d.items()
                      if k not in ("小計", "税込", "No", "src"))
            assert got == d["小計"], f"{month} {tab}: 明細 {got:,} ≠ 小計 {d['小計']:,}"
            inc = d["小計"] + round(d["小計"] * 0.1)
            assert inc == d["税込"], f"{month} {tab}: 税込 {inc:,} ≠ 請求書 {d['税込']:,}"
    return True


