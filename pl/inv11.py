def check(wb=None):
    import build2
    for tab, plrow, _m, _ex, _tax, _v, _src, _b in INV11:
        assert plrow in build2.RIDX[tab], f"{tab} に「{plrow}」行が無い"
    spot = [r for r in INV11 if r[1] == "スポット（Locoty保守）"]
    assert len(spot) == 10, f"スポットの按分が{len(spot)}か月（11月〜8月の10か月のはず）"
    assert sum(r[3] for r in spot) == 81668, "スポットの21期ぶんが81,668にならない"
    assert sum(r[4] for r in spot) == 8168, "スポットの消費税21期ぶんが8,168にならない"
    assert sum(r[3] for r in spot) + 8166 * 2 == 98000, "12か月の合計が98,000にならない"
    if wb is None:
        return
    for tab, plrow, m, ex, _tax, _v, _src, _b in INV11:
        c = wb[tab][f"{build2.MCOL[m]}{build2.RIDX[tab][plrow]}"]
        assert not c.value, (f"{tab} {plrow} {m} に既に {c.value} が入っている。"
                             f"請求書の {ex:,} を足すと二重計上になる")


