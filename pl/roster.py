#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""勤怠アプリの従業員名簿（氏名 → 所属）

利用者の指摘「前にシフト管理アプリ作ったんだけど、そこに誰がどこの所属か
わかるようになってる」（2026-08-21）。そのとおりで、このリポジトリの
    index.html    社員・本部系 12人
    kintai_part   パート・アルバイト 46人
に pin/name/dept の名簿が埋まっている。給料一覧表PDFは社員番号しか持たず、
部門コードだけでは店舗に割れないので、この名簿が橋渡しになる。

★HTMLを直接読む。アプリ側で人を足したり所属を変えたりすれば自動で追随する。

--- 何に使えて、何に使えないか（2026-08-21 実測）------------------------
使える:
    給料一覧表PDFの氏名（kyuyo_parse.names）と突き合わせると、56人中48人が
    そのまま一致する。残り8人も下の ALIAS（異体字・通称）で解ける。
    → 給与PDFの1人ずつを店舗に割り当てられる。
使えない（9月〜3月を入れ直す用途には足りない）:
    ① 現時点の名簿なので、途中で辞めた人が載っていない。
       2026年4月の給与には名簿に無い人が6人いた（飯田怜飛・市川実・渡邉肇・
       齋藤良江・濱田歩・山本英子）。
    ② 名簿の所属と、経理が実際に付けている店舗がずれることがある。
       例: 松岡実麻は名簿「バッシング」（＝神栖横丁）だが、給与集計では
           韓国酒場ハナのアルバイトとして計上されている。
    ③ 十三里屋・りゅうちゃんの法定福利費は、この名簿で割れる人からは出てこない。
    実測: 4〜7月で照合すると22行中14〜19行しか一致しない。
    → 既存21期PLから転記済みの9月〜3月を、これで上書きはしない。そちらのほうが正しい。

--- これからの使い道 -----------------------------------------------------
8月分（給料一覧表-202608.pdf）が届いたら、氏名で引いて店舗に割る下地になる。
割れない人・名簿とずれる人は保留リストへ出して指示を仰ぐこと。
22期はアプリと会計の所属をそろえておけば、そのまま自動で割れる。
"""
import os
import re

BASE = os.path.dirname(os.path.abspath(__file__))
FILES = [os.path.join(BASE, "..", "index.html"),
         os.path.join(BASE, "..", "kintai_part")]

# 給料一覧表の表記 → 勤怠アプリの表記（異体字・通称）
ALIAS = {
    "山崎悠人": "山﨑悠人",           # 崎 / 﨑
    "櫻庭京子": "桜庭京子",           # 櫻 / 桜
    "網代愛": "綱代愛",               # 網 / 綱（どちらかが誤記）
    "小金澤登美江": "小金澤登美",      # 給与のほうに「江」が付く
    "ゴラカウェラパティ": "ハルシャニ",  # 給与は本名、アプリは通称
    "ウィジェシンへアラ": "ナディシャ",
}

# 勤怠アプリの所属 → PLタブ
#   清掃の現場名（ニッセーデリカ等）はすべて業務課の仕事。
#   バッシング・横丁清掃は神栖横丁。
DEPT2TAB = {
    "業務課": "業務課",
    "ニッセーデリカ": "業務課", "トータルステイ": "業務課", "市川東病院": "業務課",
    "海事・横河": "業務課", "ちば醤油": "業務課", "香取神宮": "業務課",
    "神宮・亀甲堂・ゆう屋": "業務課", "本社": "業務課",
    "バッシング": "神栖横丁", "横丁清掃": "神栖横丁",
    "りゅうちゃん": "りゅうちゃん",
    "十三里屋": "さわら十三里屋",
    "焼きたて屋": "焼きたて屋",
    "タコハイ": "タコとハイボール",
    # 「飲食事業部」「バックオフィス」は店舗が特定できないので下の PERSON で個別に。
}

# 名簿の所属だけでは割れない人。給与の実額と既存PLを突き合わせて確定させたもの
# （2026-08-21。4〜7月の payroll.py の値と1円まで合うことを確認済み）。
PERSON = {
    "土屋芳広": "もも焼きJAPAN",
    "及川晶雄": "焼きたて屋",
    "宮川玲奈": "韓国酒場ハナ",
    "小林俊樹": "鳥害対策課",
    "石毛拓海": "神栖横丁",
    "花見朗子": "神栖横丁",
    "ハルシャニ": "タコとハイボール",
    "ナディシャ": "タコとハイボール",
    "平野健雄": "業務課", "安藤正樹": "業務課",
    "伏田幸枝": "業務課", "石毛貴英": "業務課",
    "飯田栄": "本部", "飯田純子": "本部",
}

_REC = re.compile(r"name:\s*'([^']+)',\s*dept:\s*'([^']+)'")


def load():
    """{氏名(空白なし): 所属}。勤怠アプリのHTMLから読む。"""
    out = {}
    for path in FILES:
        if not os.path.exists(path):
            continue
        for m in _REC.finditer(open(path, encoding="utf-8").read()):
            out[m.group(1).replace(" ", "").replace("　", "")] = m.group(2)
    return out


def tab_of(name):
    """給料一覧表の氏名 → PLタブ。割れなければ None。"""
    n = ALIAS.get(name, name)
    if n in PERSON:
        return PERSON[n]
    return DEPT2TAB.get(load().get(n))


if __name__ == "__main__":
    import collections
    r = load()
    print(f"勤怠アプリの名簿 {len(r)}人")
    c = collections.Counter(r.values())
    for k, v in c.most_common():
        print(f"   {k:<20}{v:>3}人  → {DEPT2TAB.get(k, '（個別判定）')}")
    try:
        import kyuyo_parse
        nm = kyuyo_parse.names("202607")
        if nm:
            ok = [n for n in nm.values() if tab_of(n)]
            ng = [n for n in nm.values() if not tab_of(n)]
            print(f"\n給料一覧表202607との突き合わせ: {len(ok)}/{len(nm)}人 割り当て可")
            if ng:
                print(f"   割れない: {ng}")
    except Exception as e:
        print("（給与PDFが無いので突き合わせは省略）", e)
