def month_of(day):
    return f"{int(day[5:7])}月"


def period_of(day):
    for p, (lo, hi) in PERIODS.items():
        if lo <= day[:7] <= hi:
            return p
    return None


def _months(period):
    """{YYYY-MM: [(start, end, fee, inc, total, name), …]}（その期のぶん）"""
    by = {}
    for r in DATA:
        start, end = r[0], r[1]
        assert start[:7] == end[:7], f"{r[5]}: 集計期間が月をまたいでいる"
        if period_of(start) == period:
            by.setdefault(start[:7], []).append(r)
    return by


def _complete(ym, parts):
    if ym in COMPLETE_ALONE:
        return True
    days = {(r[0][8:], r[1][8:]) for r in parts}
    first = any(a == "01" and b == "15" for a, b in days)
    second = any(a == "16" for a, b in days)
    return first and second


def rows(period="22期"):
    """(タブ, PL行, 月, 税抜, 消費税, 取引先, 出どころ, メモ)。半月2枚がそろった月だけ。"""
    for ym, parts in sorted(_months(period).items()):
        if not _complete(ym, parts):
            continue
        fee = sum(r[2] for r in parts)
        inc = sum(r[3] for r in parts)
        note = "収納明細書の合計行の手数料（税抜）。" + "＋".join(
            f"{r[0][5:]}〜{r[1][5:]} 手数料{r[2]:,}（決済{r[4]:,}）" for r in sorted(parts))
        if ym in COMPLETE_ALONE:
            note += "。★" + COMPLETE_ALONE[ym]
        yield (TAB, ROW, month_of(ym + "-01"), fee, inc - fee, "SBペイメントサービス",
               SRC.format(period=period), note)


def hold_rows(period="22期"):
    """半月分しか無い月。(月, タブ, 見出し, 理由)"""
    for ym, parts in sorted(_months(period).items()):
        if _complete(ym, parts):
            continue
        have = "＋".join(f"{r[0][5:]}〜{r[1][5:]} {r[2]:,}" for r in sorted(parts))
        yield (month_of(ym + "-01"), TAB, f"{ROW}（SBペイメント）",
               f"収納明細書が半月分しか無い（{have}）。もう半月ぶんが届くまで入れない"
               "（利用者指示 2026-10-08「足りない月は推測で埋めずに保留に」）")


def parse(path):
    """収納明細書PDFの合計行を読んで DATA の1行を返す。"""
    import pymupdf
    t = "\n".join(p.get_text() for p in pymupdf.open(path))
    m = re.search(r"集計期間：(\d{4})/(\d{2})/(\d{2})～(\d{4})/(\d{2})/(\d{2})", t)
    assert m, f"{path}: 集計期間が読めない"
    start = f"{m[1]}-{m[2]}-{m[3]}"
    end = f"{m[4]}-{m[5]}-{m[6]}"
    # 合計行: 件数 / 売上金額 / 返金件数 / 返金金額 / 合計件数 / 合計金額 / 手数料 / 税込金額 / お振込金額
    i = t.index("\n合計\n")
    v = [x for x in t[i:].split("\n")[2:11]]
    num = lambda s: int(s.replace("¥", "").replace(",", ""))
    total, fee, inc, pay = num(v[5]), num(v[6]), num(v[7]), num(v[8])
    assert total - inc == pay, f"{path}: 合計{total:,}−手数料税込{inc:,}≠振込{pay:,}"
    name = re.search(r"(\d{6}_収納明細書\d{4}-\d{4}_\d+)", path)
    return (start, end, fee, inc, total, name[1] if name else path)


