# -*- coding: utf-8 -*-
"""日本食研 → ハナ・もも焼きJAPAN・タコとハイボールの「仕入（日本食研）」

--- なぜ要るのか ---------------------------------------------------------
1回の振込に複数店ぶんがまとまっていて、銀行明細だけでは店舗別に割れなかった。
年計270,194円（税込）が保留のままだった。
利用者指示「日本食研は請求書で見て」（2026-08-22）。請求書に【店計】が
店舗ごとに載っていたので、そのまま割れた。

--- 元データ -------------------------------------------------------------
Dropbox  /※請求書※/買掛/21期/<請求月>月/…/（ハナ か もも焼き）/日本食研 ….pdf
ローカル  nihonshokken/<請求月>.pdf   11か月ぶん。全部スキャン画像なので目視で起こした

★ファイル名の「N月末」は支払期限。請求月は「YYYY年M月D日 締」のほう。
  例: 「日本食研　ハナ10月末.pdf」は 2025年9月30日締 ＝ 9月分。
  フォルダ（2509月 など）が請求月と一致しているので、そちらで見るのが早い。

--- 請求書の形 -----------------------------------------------------------
得意先コードと店名ごとに明細が並び、店ごとに【店計】がある。最後に
    店合計 ／ 消費税 ／ 合計 ／ (8%対象 …) (10%対象 …)
    9278338 神栖横丁 5丁目 ＝ タコとハイボール
    8795207 韓国酒場 ハナ
    8489343 もも焼JAPAN
★21期は11か月とも全額が8%軽減税率。10%対象は毎月0だった。
★店計は税抜。店合計＝各店の店計の和で、これが8%対象と一致する。

--- ポイント利用について -------------------------------------------------
7月分だけ「ポイント利用（不課税）-317」がある。もも焼JAPANの店計の下に
出るが、店合計42,658には含まれていない（合計45,753＝42,658＋3,412－317）。
支払時の値引きなので仕入の額は動かさない。店計そのままを計上する。
"""
TAB = {"タコハイ": "タコとハイボール", "ハナ": "韓国酒場ハナ", "もも焼き": "もも焼きJAPAN"}
ROW = "仕入（日本食研）"

# 請求月: {店: 店計(税抜)}, 店合計, 消費税, 合計
# 2026-08-22 に請求書11枚を目視で起こした
INVOICE = {
    "9月":  ({"ハナ": 17700},                                    17700, 1416, 19116),
    "10月": ({"ハナ": 15720},                                    15720, 1257, 16977),
    "11月": ({"ハナ": 4634, "もも焼き": 25766},                   30400, 2432, 32832),
    "12月": ({"ハナ": 18630, "もも焼き": 10150},                  28780, 2302, 31082),
    "1月":  ({"ハナ": 11100, "もも焼き": 10604},                  21704, 1736, 23440),
    "2月":  ({"ハナ": 13620},                                    13620, 1089, 14709),
    "3月":  ({"ハナ": 22760, "もも焼き": 1515},                   24275, 1942, 26217),
    "4月":  ({"ハナ": 16050, "もも焼き": 3989},                   20039, 1603, 21642),
    "5月":  ({"タコハイ": 940, "ハナ": 37623},                    38563, 3085, 41648),
    "6月":  ({"タコハイ": 3938, "ハナ": 4740, "もも焼き": 2981},   11659,  932, 12591),
    "7月":  ({"タコハイ": 5056, "ハナ": 31515, "もも焼き": 6087},  42658, 3412, 45753),
}
# 7月分だけ。もも焼JAPANの欄に出るが店合計には入っていない（説明は冒頭）
POINT = {"7月": -317}

# 6月分・7月分は inv6.py / fill2.py の INV が先に入れている
POSTED_ELSEWHERE = {"6月", "7月"}

_NEXT = {"9月": "10月", "10月": "11月", "11月": "12月", "12月": "1月", "1月": "2月",
         "2月": "3月", "3月": "4月", "4月": "5月", "5月": "6月", "6月": "7月", "7月": "8月"}


def check():
    """店計の和＝店合計＝8%対象、消費税＝8%対象×8%、店合計＋消費税＝合計。"""
    for m, (stores, sub, tax, total) in INVOICE.items():
        s = sum(stores.values())
        assert s == sub, f"{m}分: 店計の和 {s:,} ≠ 店合計 {sub:,}"
        assert sub * 8 // 100 == tax, f"{m}分: 消費税 {sub*8//100:,} ≠ 記載 {tax:,}"
        assert sub + tax + POINT.get(m, 0) == total, \
            f"{m}分: {sub:,}＋{tax:,}＋ポイント{POINT.get(m,0)} ≠ 合計 {total:,}"
    # 6月・7月は他所が入れている。値が食い違っていないか
    import inv6
    import fill2
    for m, src in (("6月", inv6.INV6), ("7月", fill2.INV)):
        mine = {TAB[k]: v for k, v in INVOICE[m][0].items()}
        theirs = {r[0]: r[3] for r in src if r[1] == "日本食研"}
        assert mine == theirs, f"{m}分が向こうと食い違う:\n  ここ {mine}\n  向こう {theirs}"


def rows():
    """(タブ, PL行, 月, 税抜, 元ファイル, メモ) を列挙。6月・7月は出さない。"""
    for m, (stores, sub, tax, total) in INVOICE.items():
        if m in POSTED_ELSEWHERE:
            continue
        yy = "25" if m in ("9月", "10月", "11月", "12月") else "26"
        src = f"買掛/21期/{yy}{int(m[:-1]):02d}月/…/日本食研 …{_NEXT[m]}末.pdf"
        for key, v in stores.items():
            yield (TAB[key], ROW, m, v, src,
                   f"請求書の【店計】。全額8%軽減税率。"
                   f"この月の店合計{sub:,}＋消費税{tax:,}＝{total:,}")


def hold_rows():
    return []


if __name__ == "__main__":
    check()
    import collections
    per = collections.Counter()
    for tab, _r, m, v, _s, _n in rows():
        per[tab] += v
    print(f"{'月':<5}" + "".join(f"{t:>14}" for t in TAB.values()))
    for m, (stores, sub, _t, _to) in INVOICE.items():
        mark = "（計上済み）" if m in POSTED_ELSEWHERE else ""
        print(f"{m:<5}" + "".join(f"{stores.get(k, 0):>14,}" for k in TAB) + f"  {mark}")
    print(f"\n入れるセル {len(list(rows()))} 件／税抜計 {sum(per.values()):,}円（9月〜5月）")
    for t, v in per.items():
        print(f"   {t:<14}{v:>10,}")
    print("検算すべて通過")
