def _k(s):
    """bank._key（全角/半角・ダッシュ・小書きカナのゆれをつぶす）＋ 先頭の「振込」を落とす。
    ★ bank._key は NFKC をかけるので、ＣＬＣ→CLC のように全角英字が半角になる。
      RULES の key もここを通してから比べる（生の文字列で比べると当たらない）。"""
    v = bank._key(s)
    return v[2:] if v.startswith("振込") else v


def _rows():
    """銀行明細の出金を (口座, 正規化した摘要, 月, 金額) で読む。"""
    out = []
    for p in sorted(glob.glob(os.path.join(DIR, "小見川支店_*.csv"))):
        base = os.path.basename(p).split("_")
        acct, ym = base[2], base[3][:6]
        if ym not in YM2M:
            continue
        for r in csv.DictReader(open(p, encoding="utf-8-sig")):
            if r["入出金区分"] != "出金":
                continue
            out.append((acct, _k(r["摘要"]), YM2M[ym],
                        int(r["出金金額(円)"] or 0), r["取引日"], r["摘要"]))
    for p in sorted(glob.glob(os.path.join(DIR, "NBG*.csv"))):
        for r in csv.DictReader(open(p, encoding="cp932")):
            if not (r["お支払金額"] or "").strip():
                continue
            ym = f'{r["操作日(年)"]}{int(r["操作日(月)"]):02d}'
            if ym not in YM2M:
                continue
            d = f'{r["操作日(年)"]}/{int(r["操作日(月)"]):02d}/{int(r["操作日(日)"]):02d}'
            out.append(("PayPay", _k(r["摘要"]), YM2M[ym],
                        int(r["お支払金額"].replace(",", "")), d, r["摘要"]))
    return out


def _eom_month(d):
    """月末引落むけのPL列。取引日 YYYY/MM/DD で、5日以前なら前月にする。

    セコムのように「月末に引き落とすが、休日にかかると翌月初になる」相手むけ。
    期の外に出たら None（21期なら 2025/09/01 の引落は20期の8月ぶん）。
    """
    y, mo, day = (int(x) for x in d.split("/"))
    if day <= 5:
        mo -= 1
        if mo == 0:
            y, mo = y - 1, 12
    return YM2M.get(f"{y:04d}{mo:02d}")


def months_with_data(acct):
    """その口座の明細CSVが手元にある月。"""
    if acct == "PayPay":
        have = {ym for ym in YM2M
                for p in glob.glob(os.path.join(DIR, "NBG*.csv"))
                if _nbg_months(p) and ym in _nbg_months(p)}
        return [YM2M[ym] for ym in sorted(YM2M) if ym in have]
    return [YM2M[ym] for ym in sorted(YM2M)
            if glob.glob(os.path.join(DIR, f"小見川支店_普通_{acct}_{ym}*.csv"))]


_NBG_CACHE = {}


def _nbg_months(path):
    if path not in _NBG_CACHE:
        ms = set()
        for r in csv.DictReader(open(path, encoding="cp932")):
            ms.add(f'{r["操作日(年)"]}{int(r["操作日(月)"]):02d}')
        _NBG_CACHE[path] = ms
    return _NBG_CACHE[path]


def missing_months():
    """明細CSVはあるのに引落が見つからない月（保留リストへ）。
    契約が終わったのか、摘要が変わったのか、CSVの取り漏れかを人が見る材料。"""
    got = collect()
    for rule in RULES:
        if not rule.get("monthly", True):
            continue        # 隔月など。間の月に引落が無いのは正常
        tab, plrow = rule["split"][0][0], rule["split"][0][1]
