def _k(s):
    """bank._key（全角/半角・ダッシュ・小書きカナのゆれをつぶす）＋ 先頭の「振込」を落とす。
    ★ bank._key は NFKC をかけるので、ＣＬＣ→CLC のように全角英字が半角になる。
      RULES の key もここを通してから比べる（生の文字列で比べると当たらない）。"""
    v = bank._key(s)
    return v[2:] if v.startswith("振込") else v


def _rows():
    """銀行明細の出金を (口座, 正規化した摘要, 月, 金額) で読む。"""
    out = []
    for p in sorted(glob.glob(os.path.join(DIR, "小見川支店_*.csv"))):
        base = os.path.basename(p).split("_")
        acct, ym = base[2], base[3][:6]
        if ym not in YM2M:
            continue
        for r in csv.DictReader(open(p, encoding="utf-8-sig")):
            if r["入出金区分"] != "出金":
                continue
            out.append((acct, _k(r["摘要"]), YM2M[ym],
                        int(r["出金金額(円)"] or 0), r["取引日"], r["摘要"]))
    for p in sorted(glob.glob(os.path.join(DIR, "NBG*.csv"))):
        for r in csv.DictReader(open(p, encoding="cp932")):
            if not (r["お支払金額"] or "").strip():
                continue
            ym = f'{r["操作日(年)"]}{int(r["操作日(月)"]):02d}'
            if ym not in YM2M:
                continue
            d = f'{r["操作日(年)"]}/{int(r["操作日(月)"]):02d}/{int(r["操作日(日)"]):02d}'
            out.append(("PayPay", _k(r["摘要"]), YM2M[ym],
                        int(r["お支払金額"].replace(",", "")), d, r["摘要"]))
    return out


def _ex(mode, gross):
    """引落額（税込）→ PLに入れる税抜。(税抜, 消費税, どう決めたか)"""
    if mode == "asis":
        return gross, 0, "非課税。引落額そのまま"
    if mode == "aono":
        # 70,000 + 7,000 − 源泉(70,000×10.21%=7,147) = 69,853
        assert gross == 69853, f"青野税理士の引落が {gross:,}（69,853のはず）"
        return 70000, 7000, "源泉7,147を戻して税抜70,000（利用者判断2026-08-20）"
    assert mode == "ex10"
    if gross % 11 == 0:
        ex = gross // 11 * 10
        return ex, gross - ex, f"引落{gross:,}÷1.1が割り切れるので税抜{ex:,}"
    return gross, 0, f"引落{gross:,}は÷1.1が割り切れないので、そのまま（税抜扱い）"


def collect():
    """{(タブ, PL行, 月): (税抜, 消費税, ルール名, 明細, 決め方)}"""
    src = _rows()
    got = {}
    for rule in RULES:
        per = collections.defaultdict(list)
        for acct, key, m, v, d, raw in src:
            if acct not in rule["accts"] or not key.startswith(_k(rule["key"])):
                continue
            per[m].append((acct, d, raw, v))
        for m, hits in per.items():
            fee = sum(rule.get("fee", {}).get(a, 0) for a, _d, _r, _v in hits)
            gross = sum(v for _a, _d, _r, v in hits) - fee
            ex, tax, how = _ex(rule["mode"], gross)
            for tab, plrow, num, den in rule["split"]:
                k = (tab, plrow, m)
                assert k not in got, f"{k} が2つのルールから来ている"
                share = ex * num // den
                detail = " ／ ".join(f"{d} {ACCT_NAME[a]} {v:,}" for a, d, _r, v in hits)
                if den != 1:
                    how = f"{how}／{den}部門で等分（{ex:,}÷{den}）"
                got[k] = (share, tax * num // den, rule["name"], detail, how)
    return got


def rows():
    """(タブ, PL行, 月, 税抜, 消費税, ルール名, 元データ, メモ) を列挙。"""
    note = {r["name"]: r["note"] for r in RULES}
    for (tab, plrow, m), (ex, tax, name, detail, how) in sorted(collect().items()):
        yield (tab, plrow, m, ex, tax, name,
               "銀行明細CSV（bank/）", f"{note[name]}。{how}。引落: {detail}")


