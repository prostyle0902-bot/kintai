def check(wb=None):
    """行の存在と、既存PL（CHECK）との一致を確かめる。

    wb を渡すと「これから入れるセルが空か」も見る。二重計上を止めるため。
    ADD_ON のセルだけは先に入っている額と一致することを確かめて通す。
    """
    import build2
    got = collect()
    for tab, plrow, m in got:
        assert plrow in build2.RIDX[tab], f"{tab} に「{plrow}」行が無い"
        assert m in build2.MCOL, m
    for (tab, plrow), want in CHECK.items():
        for m, v in want.items():
            k = (tab, plrow, m)
            assert k in got, f"{tab} {plrow} {m} が銀行から拾えていない"
            if k in EXCEPT:
                assert got[k][0] == EXCEPT[k][0], (
                    f"{tab} {plrow} {m}: 銀行から {got[k][0]:,} だが "
                    f"EXCEPT は {EXCEPT[k][0]:,} を想定している。銀行データが変わった？")
                continue
            assert got[k][0] == v, (f"{tab} {plrow} {m}: 銀行から {got[k][0]:,} だが "
                                    f"既存PLは {v:,}")
    # ★毎月これを回す前提なので、月数は決め打ちにしない（利用者指示 2026-09-02「毎月お願い」）。
    #   「その口座の明細CSVが手元にある月」だけを対象にする。CSVが増えれば
    #   そのぶん自動で増え、まだ届いていない月では落ちない。
    #   CSVがあるのに引落が見つからない月は missing_months() が保留リストへ出す。
    for rule in RULES:
        assert any(k[0] == rule["split"][0][0] and k[1] == rule["split"][0][1]
                   for k in got), f"{rule['name']} の引落が1件も見つからない"
    if wb is None:
        return True
    #   ★すでに埋まっているセルは「請求書などが先に入れた」もの。飛ばすが、
    #     そのとき金額が引落と一致することを確かめる（重なりは検算材料）。
    for (tab, plrow, m), (ex, _tax, _n, _d, _h) in sorted(got.items()):
        v = wb[tab][f"{build2.MCOL[m]}{build2.RIDX[tab][plrow]}"].value
        if not v:
            continue
        add = ADD_ON.get((tab, plrow, m))
        if add:
            assert int(v) == add[0], (f"{tab} {plrow} {m}: 先に入っている {int(v):,} が "
                                      f"ADD_ON の {add[0]:,} と違う")
            continue
        assert int(v) == ex, (f"{tab} {plrow} {m}: 先に入っている {int(v):,} と "
                              f"引落からの {ex:,} が違う。どちらかが間違っている")
    return True


