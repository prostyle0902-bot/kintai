#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""椎名環境整備の産廃処分（大口2件）→ 本部「椎名環境」

--- なぜ要るのか ---------------------------------------------------------
銀行明細に椎名環境整備への大きな支払いが2回だけあった。
    2025/11/28  242,000円
    2026/05/29  221,100円
毎月の定額は13,200円（十三里屋の廃棄物処分）なので、桁が違う。
fixed_costs.py の定額12,000では拾えず、既存PLにも入っていなかった。
利用者に確認したところ「本部に入れて。産廃処分費です」（2026-08-21）。

--- 元データ -------------------------------------------------------------
請求書PDFが【業務】フォルダにあった。十三里屋あての毎月分とは別物。
    /※請求書※/買掛/21期/2510月/確認済/業務/支払済/椎名環境整 11月末.pdf
    /※請求書※/買掛/21期/2604月/確認済/業務/椎名環境整備　5月末.pdf
ローカル  shiina/業務_<請求月>.pdf
どちらもスキャン画像でテキスト層は無い。目視で起こした。

★ファイル名が「椎名環境整備」と「椎名環境整」で揺れている。
  「椎名環境整備」で検索すると2510月分が引っかからない。「椎名環境整」で探すこと。
★21期の【業務】フォルダにある椎名環境整備の請求書はこの2枚だけ。
  （十三里屋あては9月分〜7月分の11枚。そちらは fixed_costs.py が定額で持っている）

--- 請求書の中身 ---------------------------------------------------------
10月分（発行 2025/10/31）  課税10%対象小計 220,000 ／ 消費税 22,000 ／ 合計 242,000
    2025/10/29  混合廃棄物処分費              10 ㎥  @18,000 = 180,000
                収集処分運搬費（人件費.車両費込） 2 台  @20,000 =  40,000
                場所: 本社倉庫                       ← ★本部で正しい
4月分（発行 2026/4/30）    課税10%対象小計 189,000 ／ 消費税 18,900 ／ 合計 207,900
    2026/4/2    混廃廃棄物処分                 3 台  @45,000 = 135,000
                収集運搬費（運搬費・人件費）     3 台  @18,000 =  54,000
                現場名: 事務所                       ← ★本部で正しい

--- 銀行との突き合わせ（2026-08-21 実測）-------------------------------
10月分  請求書 242,000 ＝ 2025/11/28 PayPay 242,000    そのまま一致
4月分   請求書 207,900 ＋ 十三里屋4月分 13,200 ＝ 2026/05/29 PayPay 221,100
        ★5月末の1回で、本部の産廃と十三里屋の毎月分がまとめて振り込まれている。
          十三里屋の13,200（税抜12,000）は fixed_costs.py が既に持っているので、
          ここでは本部の 189,000 だけを入れる。二重計上にならない。

--- 計上月 ---------------------------------------------------------------
請求書の請求月をそのままPL列にする（作業日も請求月の中に入っている）。
    10月分 … 作業日 2025/10/29 → 10月
     4月分 … 作業日 2026/4/2   →  4月
支払いは翌月末（月ズレ1か月）。ほかのモジュールと同じ。

--- 椎名環境整備への支払い 611,120円（税込）の内訳 ---------------------
    本部  産廃処分  242,000 ＋ 207,900              = 449,900   ← このモジュール
    十三里屋 毎月分 13,310×2 ＋ 13,200×8            = 132,220   ← fixed_costs.py
    ★シイナ　ユウイチ 2025/09/12 PayPay             =  29,000   ← 保留のまま
                                                     ---------
                                                       611,120
29,000は個人名あて・9/12の1件だけで、請求書が見当たらない。推測で入れない。

--- 気づいたこと（直していない）-----------------------------------------
十三里屋の毎月分は、千葉銀行の頃（9月分）が13,310＝税抜12,100で、
PayPayに移ってから（11月分〜）は13,200＝税抜12,000。
fixed_costs.py は11か月とも12,000なので、9月だけ100円少ない。実害は小さい。
"""
TAB, ROW = "本部", "椎名環境"

# 請求月: (税抜, 消費税, 合計, 作業日, 場所, 明細, 支払日, 支払額, 元ファイル)
INVOICE = {
    "10月": (220000, 22000, 242000, "2025/10/29", "本社倉庫",
             "混合廃棄物処分費 10㎥@18,000=180,000／"
             "収集処分運搬費（人件費.車両費込）2台@20,000=40,000",
             "2025/11/28", 242000,
             "買掛/21期/2510月/確認済/業務/支払済/椎名環境整 11月末.pdf"),
    "4月":  (189000, 18900, 207900, "2026/4/2", "事務所",
             "混廃廃棄物処分 3台@45,000=135,000／"
             "収集運搬費（運搬費・人件費）3台@18,000=54,000",
             "2026/05/29", 221100,
             "買掛/21期/2604月/確認済/業務/椎名環境整備　5月末.pdf"),
}
# 4月分の振込には十三里屋の毎月分が相乗りしている（税込。fixed_costs.py が計上済み）
RIDE_ALONG = {"4月": 13200}


def rows():
    """(タブ, PL行, 月, 税抜, 元ファイル, メモ) を列挙。"""
    for m, (ex, tax, total, work, place, detail, pay, paid, src) in INVOICE.items():
        note = f"産廃処分（{place}／作業日 {work}）。{detail}。"
        ride = RIDE_ALONG.get(m)
        if ride:
            note += (f"請求書合計{total:,}＋十三里屋の毎月分{ride:,}＝"
                     f"{pay} の振込{paid:,}と一致")
        else:
            note += f"請求書合計{total:,}＝{pay} の振込{paid:,}と一致"
        yield (TAB, ROW, m, ex, src, note)


def check(wb=None):
    """請求書の内部整合と、銀行の振込額との突き合わせ。"""
    for m, (ex, tax, total, _w, _p, _d, pay, paid, _s) in INVOICE.items():
        assert ex * 10 // 100 == tax, f"{m}分: 消費税 {ex*10//100:,} ≠ 記載 {tax:,}"
        assert ex + tax == total, f"{m}分: {ex:,}＋{tax:,} ≠ 合計 {total:,}"
        assert total + RIDE_ALONG.get(m, 0) == paid, \
            f"{m}分: 請求書{total:,}＋相乗り{RIDE_ALONG.get(m,0):,} ≠ 振込{paid:,}（{pay}）"
    if wb is None:
        return
    import build2
    assert ROW in build2.RIDX[TAB], f"{TAB} に「{ROW}」行が無い"
    for tab, plrow, m, val, _src, _note in rows():
        c = wb[tab][f"{build2.MCOL[m]}{build2.RIDX[tab][plrow]}"]
        assert not c.value, (f"{tab} {plrow} {m} に既に {c.value} が入っている。"
                             f"産廃の {val:,} を足すと二重計上になる")


def hold_rows():
    """保留リストへ出すもの。"""
    return [("9月", "本部", "椎名環境整備（シイナ　ユウイチ）",
             "2025/09/12 PayPay 29,000円。年計611,120の内訳は "
             "産廃449,900（本部へ計上）＋十三里屋の毎月分132,220（計上済み）"
             "＋この29,000。個人名あてで請求書が見当たらず、"
             "毎月分とも産廃とも金額が合わない。推測で入れない")]


if __name__ == "__main__":
    check()
    for tab, plrow, m, val, src, note in rows():
        print(f"{tab} {plrow} {m}  {val:>9,}  {note}")
    print(f"\n計 {sum(r[3] for r in rows()):,}円（税抜）")
    print("検算すべて通過")
