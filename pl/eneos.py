#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ENEOS BUSINESS Ⅱ（トヨタファイナンス）の給油代 → 業務課「トヨタファイナンス（燃料）」

--- 元データ -------------------------------------------------------------
Dropbox /※請求書※/買掛/21期/YYMM月/…/業務/ENEOS_YYYYMM.csv   CP932

★★ ファイル名の年月は【引落月】。利用月ではない ★★
    引落は利用月の2か月後。だからフォルダは「利用月」にしてある。
        ENEOS_202511.csv → お支払日 2025/11/4 → 利用日 25/9/15〜25/9/26 → 9月列
        ENEOS_202609.csv → お支払日 2026/9/2 → 利用日 26/7/18〜26/7/31 → 7月列
    21期は ENEOS_202511 〜 ENEOS_202609 の11ファイル。

    ※陸事総合（rikuji.py）はファイル名が【利用月】。逆なので間違えないこと。

--- CSVの構造 -----------------------------------------------------------
    "今回のご請求内容","2025年11月"          ← 引落月
    "お支払日","ご請求金額合計（Ａ）",…
    "2025年11月 4日",101583,"自動振替",…
    …
    給油明細が1件1行。日付・油種・数量・金額・消費税・SS名
    最終行が「ご請求金額合計（Ａ）」で、列7=税込, 列9=消費税

--- PL行への割り当て -----------------------------------------------------
    業務課「トヨタファイナンス（燃料）」← 税抜（＝請求金額合計 − 消費税）

--- ★既存PLが壊れていた（2026-08-20 判明）------------------------------
既存の業務課シートは
    1月〜6月 … 税込をそのまま入れていた
    9月〜12月… 税込でも税抜でもない数字（9月79,979／12月49,410 など）。出所不明
    7月     … 空欄
年計で 既存799,071 に対し、正しい税抜は 961,911。約16万円ぶん少なかった。
このモジュールで全部を正しい税抜に入れ替える。
"""
import csv, os

DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "eneos")
TAB, ROW = "業務課", "トヨタファイナンス（燃料）"
MONTHS = ["9月", "10月", "11月", "12月", "1月", "2月", "3月",
          "4月", "5月", "6月", "7月"]
# PL列 -> 引落月（ファイル名）。利用月+2か月。
PAY_MONTH = {"9月": "202511", "10月": "202512", "11月": "202601", "12月": "202602",
             "1月": "202603", "2月": "202604", "3月": "202605", "4月": "202606",
             "5月": "202607", "6月": "202608", "7月": "202609"}

# 既存PLの値（2026-08-20 読み取り）。入れ替えるので検算には使わない。参考。
EXIST_21 = {"9月": 79979, "10月": 71727, "11月": 83651, "12月": 49410,
            "1月": 62137, "2月": 95075, "3月": 97516, "4月": 75799,
            "5月": 85557, "6月": 98220, "7月": None}


def _read(month):
    """(税込, 消費税, 給油件数, 支払日) を返す"""
    path = os.path.join(DIR, f"ENEOS_{month}.csv")
    raw = open(path, "rb").read().decode("cp932")
    rows = list(csv.reader(raw.splitlines()))
    total, n, payday = None, 0, ""
    for r in rows:
        if len(r) >= 4 and r[0] and "お支払日" not in r[0] and "年" in r[0] and "日" in r[0]:
            payday = payday or r[0]
        if len(r) > 10 and "ご請求金額合計" in str(r[4]):
            total = (int(r[7]), int(r[9] or 0))
        elif len(r) > 10 and r[3] and "/" in r[3]:
            n += 1
    assert total, f"{path}: 「ご請求金額合計（Ａ）」の行が見つからない"
    return total[0], total[1], n, payday


def rows():
    """(タブ, PL行, 月, 税抜, 元ファイル, メモ) を列挙"""
    for m in MONTHS:
        inc, tax, n, payday = _read(m)
        yield (TAB, ROW, m, inc - tax,
               f"買掛/21期/{'25' if m in ('9月','10月','11月','12月') else '26'}"
               f"{int(m[:-1]):02d}月/…/業務/ENEOS_{PAY_MONTH[m]}.csv",
               f"税込{inc:,} − 消費税{tax:,}。給油{n}件。支払日 {payday}")


def check():
    """税込 − 消費税 = 税抜 が全月で成り立つことと、件数が0でないことを確認"""
    for m in MONTHS:
        inc, tax, n, payday = _read(m)
        assert inc > 0 and 0 < tax < inc, f"{m}: 税込{inc:,} 消費税{tax:,} がおかしい"
        assert n > 0, f"{m}: 給油明細が0件"
    return True


if __name__ == "__main__":
    check()
    print(f"{TAB} / {ROW}\n")
    print(f"{'月':<5}{'税込':>10}{'消費税':>9}{'税抜':>10}{'件数':>6}   既存PL")
    print("-" * 62)
    t = 0
    for tab, row, m, ex, src, note in rows():
        inc, tax, n, _ = _read(m)
        e = EXIST_21[m]
        mark = "空欄" if e is None else (f"{e:,}" + ("（税込）" if e == inc else "（?）"))
        print(f"{m:<5}{inc:>10,}{tax:>9,}{ex:>10,}{n:>6}   {mark}")
        t += ex
    print("-" * 62)
    print(f"{'計':<5}{'':>10}{'':>9}{t:>10,}")
    old = sum(v for v in EXIST_21.values() if v)
    print(f"\n既存PL年計 {old:,} → 正しい税抜 {t:,}（差 {t-old:+,}）")
