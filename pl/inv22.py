GETSUMATSU = {("業務課", "外注費（ライズ）")}


def due_end(m, d=None):
    """22期の『m』月の30日になったか（2月は30日が無いので最後の日）。10月なら10/30から"""
    import calendar
    import datetime
    y, mm = _M22[m]
    d = d or today()
    return d >= datetime.date(y, mm, min(30, calendar.monthrange(y, mm)[1]))


