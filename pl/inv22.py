def today():
    """試すときは PL_TODAY=2026-11-01 のように渡す"""
    import datetime
    t = os.environ.get("PL_TODAY")
    return datetime.date.fromisoformat(t) if t else datetime.date.today()


def due(m, d=None):
    """22期の『m』月が来ているか（その月の1日以降か）"""
    y, mm = _M22[m]
    d = d or today()
    return (d.year, d.month) >= (y, mm)


