def _bank_index():
    """{摘要キー: {(支払日, 銀行): 金額}}。銀行明細を実際に引き直す。"""
    d = collections.defaultdict(dict)
    for date, bk, raw, _v, amt, _src, _known in bank.payments():
        for key in ("エムイ", "ヒラノ　タカシ", "キヨウサイ",
                    "イイダ　サカエ", "コバヤシ　トシキ", "ヒラノ　タケオ", "イシゲ　タカヒデ"):
            if key in raw:
                d[key][(date, bk)] = d[key].get((date, bk), 0) + amt
    return d


