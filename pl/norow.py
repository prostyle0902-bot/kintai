    idx = _bank_index()
    # ① 計上額＋手数料が、銀行明細の実額とぴったり合うこと
    for tab, plrow, m, ex, inc, pay, bk, key, _src, _note in POSTINGS:
        assert (pay, bk) in idx[key], \
            f"{plrow} {m}: 銀行明細に {pay} {bk} の支払いが無い"
        actual = idx[key][(pay, bk)]
        fee = FEES.get((key, pay), 0)
        assert inc + fee == actual, \
            (f"{plrow} {m}: 税込{inc:,}＋手数料{fee:,} ≠ 銀行の{actual:,}"
             f"（{pay} {bk}）")
    # ② MEGは請求書に税率10%と書いてあるので税抜から税込が出せること
