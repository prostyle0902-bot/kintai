# ダッシュ類のゆれ。銀行によって − ー － ‐ - が混ざる
_DASH = "\u2212\u30fc\uff0d\u2010\u2013\u2014-"


# 小書きカナのゆれ。同じ相手でも「キユウヨ」と「キュウヨ」の両方が出てくる
_SMALL = str.maketrans("ァィゥェォャュョッヮ", "アイウエオヤユヨツワ")


def _key(s):
    """摘要・取引先名を突き合わせ用のキーにする。

    ★ゆれが3種類ある。全部つぶしてから比べる。
      1. 全角/半角          NFKC で吸収
      2. ダッシュの種類      千葉銀行「ＣＬＣリ−ス」(U+2212) と
                            PayPay「クリ－ズコネクト」(U+FF0D) が混在
      3. 小書きカナ         「キユウヨシキン」と「キュウヨシキン」が両方ある
    """
    s = unicodedata.normalize("NFKC", str(s))
    s = re.sub(f"[{_DASH}]", "", s)
    s = re.sub(r"[（）()株式会社有限会社合同会社\s・．\.　]", "", s)
    return s.translate(_SMALL)


_norm = _key      # 旧名。PL側の取引先名にも同じ正規化を使う


def _load_chiba():
    for path in sorted(glob.glob(os.path.join(DIR, "*小見川支店*.csv"))):
        for r in csv.DictReader(open(path, encoding="utf-8-sig")):
            if not r["出金金額(円)"]:
                continue
            yield {"date": r["取引日"], "bank": "千葉銀行",
                   "raw": r["摘要"].strip(), "amount": int(r["出金金額(円)"]),
                   "src": os.path.basename(path)}


def _load_paypay(pattern="NBG*.csv"):
    for path in sorted(glob.glob(os.path.join(DIR, pattern))):
        for r in csv.DictReader(open(path, encoding="cp932")):
            if not r["お支払金額"] or r["摘要"] == "振込手数料":
                continue
            d = (f"{r['操作日(年)']}/{int(r['操作日(月)']):02d}/"
                 f"{int(r['操作日(日)']):02d}")
            yield {"date": d, "bank": "PayPay銀行",
                   "raw": r["摘要"].replace("振込 ", "").strip(),
                   "amount": int(r["お支払金額"]),
                   "src": os.path.basename(path)}


_VMAP = None


def _match(raw):
    """摘要 → (PL取引先名 or None, 判定できたか)。正規化して前方一致。"""
    global _VMAP
    if _VMAP is None:
        _VMAP = sorted(((_key(k), v) for k, v in VENDOR.items()),
                       key=lambda x: -len(x[0]))
    r = _key(raw)
    if not r:
        return None, False               # 摘要が空。中身が分からないので未判定
    for k, v in _VMAP:
        if not k:
            continue
        # ★千葉銀行の摘要は14文字で切れる。「ニホンビルメンケイエイヒ」のように
        #   対応表のキーより短くなるので、逆向きの前方一致も見る。
        #   短すぎる一致は誤爆するので8文字以上のときだけ。
        if r.startswith(k) or (len(r) >= 8 and k.startswith(r)):
            return v, True
    for k in IGNORE_CHIBA:
        kk = _key(k)
        if r.startswith(kk) or (len(r) >= 8 and kk.startswith(r)):
            return None, True
    if any(r.startswith(_key(k)) for k in UNRESOLVED):
        return None, True
    return None, False


def payments():
    """全銀行の出金を (日付, 銀行, 摘要, PL取引先, 金額, 元ファイル) で列挙"""
    for r in list(_load_chiba()) + list(_load_paypay()):
        vendor, known = _match(r["raw"])
        yield (r["date"], r["bank"], r["raw"], vendor, r["amount"],
               r["src"], known)


def unknown():
    """対応表に無い摘要を、件数・金額つきで返す。VENDOR に追記していく。"""
    agg = collections.Counter(); amt = collections.Counter()
    for date, bank, raw, vendor, a, src, known in payments():
        if not known:
            agg[raw] += 1; amt[raw] += a
    return [(raw, n, amt[raw]) for raw, n in agg.most_common()]


def pl_vendors(wb):
    """PL側の取引先を {正規化名: 税抜合計} で返す。

    2つの経路をどちらも見る:
      ・明細ログの「取引先」列  … 請求書・カード明細から入ったもの
      ・PLの行名               … 取引先名がそのまま行になっているもの
                                （本部のTMAP・リコーリース、業務課の陸自総合など）
    ★行名も見ないと「PLに無い」の誤検知だらけになる。
    """
    import build2
    out = collections.Counter()
    ws = wb["明細ログ"]
    h = [c.value for c in ws[2]]
    iv, ie = h.index("取引先"), h.index("税抜")
    for r in ws.iter_rows(min_row=3, values_only=True):
        if r[iv]:
            out[_norm(r[iv])] += int(r[ie] or 0)
    for tab in build2.TABS:
        for kind, name, _ in build2.layout_for(tab):
            if kind != "IN":
                continue
            row = build2.RIDX[tab][name]
            tot = sum(int(wb[tab][build2.MCOL[m] + str(row)].value or 0)
                      for m in build2.MONTHS)
            out[_norm(name)] += tot
    return out


def _hit(n, pool):
    return n in pool or any(n in k or k in n for k in pool if len(k) > 3)


def reconcile(wb):
    """(完全に無い, 行はあるが金額ゼロ, 計上あり, PLだけにある) を返す。

    金額の月次一致は見ない。1回の振込に複数月ぶんがまとまることがあるので、
    取引先レベルの有無だけ見る。
    """
    bank = collections.Counter()
    for date, b, raw, vendor, a, src, known in payments():
        if vendor and not vendor.startswith("＠"):
            bank[vendor] += a
    pl = pl_vendors(wb)
    nonzero = {k for k, v in pl.items() if v}
    missing, zero, ok = [], [], []
    for v, a in sorted(bank.items(), key=lambda x: -x[1]):
        n = _norm(v)
        if _hit(n, nonzero):
            ok.append((v, a))
        elif _hit(n, pl):
            zero.append((v, a))          # 行はあるが1円も入っていない
        else:
            missing.append((v, a))       # 行すら無い
    bank_norm = {_norm(v) for v in bank}
    only_pl = sorted(((k, a) for k, a in pl.items()
                      if a and not _hit(k, bank_norm)), key=lambda x: -x[1])
    return missing, zero, ok, only_pl


def hold_rows():
    """保留: 正体が分からない支払先"""
    tot = collections.Counter()
    for date, b, raw, vendor, a, src, known in payments():
        if raw in UNRESOLVED:
            tot[raw] += a
    for raw, why in UNRESOLVED.items():
        yield ("21期通年", raw, tot[raw], why)


