"""本部の毎月定額の自動引落 → 本部タブ

請求書が来ない。銀行から毎月同じ額が自動で引き落とされるだけなので、
元データは既存の本部PLスプシしかない。
    file_id 1xO2MPtct0XSPVOC_d9TxRdZpTXGv9tqM6gewF8TxuYk
    2026-08-20 に読み取り

--- 入れる条件 ----------------------------------------------------------
既存スプシの 9月〜7月の11か月が【全部同じ額】の行だけ。
1か月でも違う額があるものは入れない（都度請求の可能性が高いため）。

入れなかった行と、その理由:
    高塚誠            10,000 だが4月だけ 15,000
    帝国データバンク     3,300 だが2月だけ 99,000
    リコーリース        41,800 だが9月 51,196・11月 53,284
    三井住友リース       8,580 だが11月 88,220
    CCMOコンサルティング 60,000 だが5月 71,000
    NS会議所          12月まで26,650、1月から18,490（期の途中で変更）
    オニオン新聞        5月まで22,500、6月から172,500（期の途中で変更）
これらは請求書やカード明細から入る（inv6/inv7/cards）ので、
ここで入れると二重計上になる。

--- 消費税の扱い（利用者判断 2026-08-20）--------------------------------
「割り切れる2行だけ税抜に直す」。
既存スプシは税抜が原則だが、÷1.1 がちょうど割り切れる2行は税込のまま
入っていたと判断できるので、そこだけ直す。
    フォーゲル弁護士事務所 55,000 → 50,000  （55,000÷1.1 = 50,000ちょうど）
    五十嵐商会              2,530 →  2,300  （ 2,530÷1.1 =  2,300ちょうど）
残り8行は ÷1.1 が割り切れず、税抜か税込か数字からは判断できないので触らない。
保険2行（ジブラルタ生命・プルデンシャル生命）は非課税なのでそもそも対象外。

--- 対象月（利用者判断 2026-08-20）-------------------------------------
9月〜7月の11か月だけ。8月は月が締まっていないので入れない。
8月分をまとめて処理するとき（9月10日のリマインド）に MONTHS へ "8月" を足す。
"""

TAB = "本部"
MONTHS = ["9月", "10月", "11月", "12月", "1月", "2月", "3月",
          "4月", "5月", "6月", "7月"]          # ★8月は入れない

# PL行 -> (既存スプシの毎月の額, 実際に入れる額, メモ)
FIXED = {
    "青野税理士":            (69853, 69853, ""),
    "フォーゲル弁護士事務所":  (55000, 50000, "既存は税込。÷1.1が割り切れるので税抜に直した"),
    "地代家賃（145,000÷3）":  (48333, 48333, "145,000円を3部門で割った1/3"),
    "プルデンシャル生命":      (47090, 47090, "保険料・非課税"),
    "リヴィン":              (45486, 45486, ""),
    "千葉銀リース":           (21800, 21800, ""),
    "JBQ":                  (20000, 20000, ""),
    "ジブラルタ生命":         (17345, 17345, "保険料・非課税"),
    "セコム":                (16200, 16200, ""),
    "五十嵐商会":             (2530,  2300, "既存は税込。÷1.1が割り切れるので税抜に直した"),
}

# 定額でないので入れない行（検算とドキュメントのため残す）
NOT_FIXED = {
    "高塚誠":              "10,000だが4月だけ15,000",
    "帝国データバンク":      "3,300だが2月だけ99,000",
    "リコーリース":         "41,800だが9月51,196・11月53,284",
    "三井住友リース":        "8,580だが11月88,220",
    "CCMOコンサルティング":  "60,000だが5月71,000",
    "NS会議所（上乗せ労災）": "12月まで26,650、1月から18,490",
    "オニオン新聞":         "5月まで22,500、6月から172,500",
}

SRC = "既存スプシ「本部 損益計算書」（自動引落・請求書なし）"


def rows():
    """(タブ, PL行, 月, 金額, 元, メモ) を列挙。"""
    for plrow, (orig, use, note) in FIXED.items():
        for m in MONTHS:
            yield TAB, plrow, m, use, SRC, note


def check(wb=None):
    """二重計上していないか確認する。

    wb を渡すと、いま入れようとしているセルが空であることを確認する。
    請求書やカード明細が同じ行に入っていたら、そこで止める。
    """
    if wb is None:
        return True
    import build2
    R = build2.RIDX[TAB]
    for plrow in FIXED:
        for m in MONTHS:
            v = wb[TAB][build2.MCOL[m] + str(R[plrow])].value
            assert not v, (f"{plrow} {m} にすでに {v} が入っている。"
                           f"請求書・カード明細と二重計上になる")
    return True


if __name__ == "__main__":
    print(f"本部の毎月定額（{len(FIXED)}行 × {len(MONTHS)}か月 = "
          f"{len(FIXED) * len(MONTHS)}セル）\n")
    total = 0
    print(f"{'行':<24}{'既存':>9}{'入れる':>9}{'11か月':>11}  メモ")
    print("-" * 88)
    for plrow, (orig, use, note) in FIXED.items():
        t = use * len(MONTHS); total += t
        mark = "" if orig == use else f"  ← 既存 {orig:,}"
        print(f"{plrow:<24}{orig:>9,}{use:>9,}{t:>11,}  {note}")
    print("-" * 88)
    print(f"{'合計':<24}{'':>9}{'':>9}{total:>11,}")
    print("\n入れない行（定額ではない）:")
    for k, v in NOT_FIXED.items():
        print(f"  {k:<22} {v}")
